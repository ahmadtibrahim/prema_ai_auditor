from odoo.tests.common import TransactionCase

from odoo.addons.prema_ai_auditor.services import crm_operator


class TestCrmOperatorBase(TransactionCase):
    @classmethod
    def setUpClass(cls):
        super().setUpClass()
        cls.Lead = cls.env['crm.lead']
        cls.Stage = cls.env['crm.stage']
        cls.admin = cls.env.ref('base.user_admin')
        # canonical stages (xmlid resolution like the service uses)
        cls.st_new = cls.env.ref('premafirm_ai_engine.crm_stage_new_uncontacted')
        cls.st_outreach = cls.env.ref('premafirm_ai_engine.crm_stage_outreach_sent')
        cls.st_engaged = cls.env.ref('premafirm_ai_engine.crm_stage_engaged_replied')
        cls.st_onboarding = cls.env.ref('premafirm_ai_engine.crm_stage_onboarding')
        cls.st_paused = cls.env.ref('premafirm_ai_engine.crm_stage_paused')
        cls.st_lost = cls.env.ref('premafirm_ai_engine.crm_stage_lost')
        cls.call_type = cls.env['mail.activity.type'].search(
            [('name', '=', 'Call')], limit=1)

    def _make_lead(self, name='Fixture Co', **kw):
        vals = {
            'name': name,
            'type': 'opportunity',
            'stage_id': self.st_outreach.id,
            'user_id': self.admin.id,
        }
        vals.update(kw)
        return self.Lead.create(vals)


class TestCrmOperatorRead(TestCrmOperatorBase):

    def test_call_list_prioritizes_overdue_calls(self):
        lead_a = self._make_lead('Alpha Foods', partner_name='Alpha Foods')
        lead_b = self._make_lead('Beta Distributors', partner_name='Beta Distributors',
                                 stage_id=self.st_engaged.id)
        # overdue call on A (today - 3), call due today on B
        self.env['mail.activity'].create({
            'activity_type_id': self.call_type.id,
            'res_id': lead_a.id,
            'res_model_id': self.env['ir.model']._get_id('crm.lead'),
            'user_id': self.admin.id,
            'summary': 'Call Alpha',
            'date_deadline': '2020-01-01',
        })
        self.env['mail.activity'].create({
            'activity_type_id': self.call_type.id,
            'res_id': lead_b.id,
            'res_model_id': self.env['ir.model']._get_id('crm.lead'),
            'user_id': self.admin.id,
            'summary': 'Call Beta',
            'date_deadline': '2020-01-01',
        })
        out = crm_operator.op_get_call_list(self.env)
        self.assertGreaterEqual(out['count'], 2)
        # overdue-first ordering
        companies = [c['company'] for c in out['call_list']]
        self.assertEqual(companies[0], 'Alpha Foods')

    def test_overdue_activities(self):
        lead = self._make_lead('Overdue Co')
