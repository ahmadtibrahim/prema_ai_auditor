"""PHASE 43 — CRM operator mode tests.

Covers:
  AI READ  — call list, overdue follow-ups, pipeline summary, lead
             lookup, lead timeline
  AI WRITE — move stage, create activity, internal note, assign
             salesperson, pause/resume, mark Won/Lost, tags
  SECURITY — ACL scope (AI cannot touch leads outside the acting user's
             record rules), no arbitrary models / ORM commands, audit
             notes are internal (mt_note, never emailed), no customer
             email generated by audit logging.
"""
import json

