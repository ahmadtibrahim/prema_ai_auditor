    def test_fallback_write_flows_through_dispatch_and_audits(self):
        """Regression for the live failure: LLM router refuses the request
        (is_crm_operator=false) → the fallback must take over. Since the
        2026-08-31 preview-every-write decision the write PREVIEWS first;
        an explicit 'confirm' then executes it through dispatch(), where
        ACL + audit log apply."""
        from unittest import mock
        lead = self._make_lead('AuditFallback Co')
        session = self.env['prema.ai.session'].create({'name': 'FallbackD'})
        with mock.patch.object(
                session.__class__, '_call_responses_text',
                return_value='{"is_crm_operator": false}'):
            reply = session._handle_crm_operator_request(
                'Add an internal note to AuditFallback Co: spoke with John')
        self.assertIsInstance(reply, str)
        self.assertIn('AuditFallback Co', reply)
        # preview only — nothing applied, nothing audited yet
        self.assertTrue(session.crm_pending_preview)
        self.assertEqual(self.env['prema.ai.crm.action'].search_count(
            [('lead_id', '=', lead.id),
             ('action', '=', 'add_internal_note')]), 0)
        self.assertFalse(any('spoke with John' in (m.body or '')
                             for m in lead.message_ids))
        # explicit confirmation executes the write + audit
        result = session.send_message('confirm')
        self.assertIsInstance(result, dict)
        self.assertEqual(self.env['prema.ai.crm.action'].search_count(
            [('lead_id', '=', lead.id),
             ('action', '=', 'add_internal_note')]), 1)
        notes = lead.message_ids.filtered(
            lambda m: m.subtype_id == self.env.ref('mail.mt_note'))
        self.assertTrue(any('spoke with John' in (n.body or '') for n in notes))
        self.assertFalse(session.crm_pending_preview)

    def test_chat_confirms_pending_preview_without_keywords(self):
        """Regression: 'yes, go ahead' contains no CRM keyword, so the
        keyword gate skipped the operator handler and the LLM only wrote
        a confirmation-style reply — nothing executed. A pending preview
        must force the operator path, and 'go ahead' must execute it."""
        lead = self._make_lead('Confirm Co')
        session = self.env['prema.ai.session'].create({'name': 'Confirm'})
        session.crm_pending_preview = json.dumps({
            'intent': 'mark_won',
            'params': {'lead_ids': [lead.id], 'request_text': 'mark won'},
        })
        reply = session.send_message('yes, go ahead')
        # send_message returns {'reply': str, 'pending_action': ...}
        self.assertIn('WON', reply['reply'])
        self.assertEqual(lead.stage_id.name, 'WON / ACTIVE CUSTOMER')
        logs = self.env['prema.ai.crm.action'].search(
            [('lead_id', '=', lead.id), ('action', '=', 'mark_won')])
        self.assertEqual(len(logs), 1)
        self.assertFalse(session.crm_pending_preview)

