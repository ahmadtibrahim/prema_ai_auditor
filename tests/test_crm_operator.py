class TestCrmOperatorSecurity(TestCrmOperatorBase):
    @classmethod
    def setUpClass(cls):
        super().setUpClass()
        cls.limited = cls.env['res.users'].create({
            'name': 'CRM Portal-ish User',
            'login': 'crm_limited_%s' % cls.id,
            'groups_id': [(6, 0, [
                cls.env.ref('base.group_user').id,
            ])],
        })
        # restrict this user with a record rule: only leads they own
        cls.env['ir.rule'].create({
            'name': 'Test rule: own leads only',
            'model_id': cls.env.ref('crm.model_crm_lead').id,
            'domain_force': "[('user_id', '=', user.id)]",
            'groups': [(6, 0, [cls.env.ref('base.group_user').id])],
        })

    def test_ai_cannot_touch_lead_outside_user_scope(self):
        admin_lead = self._make_lead('Admin Only Co', user_id=self.admin.id)
        other_env = self.env(user=self.limited.id)
        # read blocked by record rule
        with self.assertRaises(AccessError):
            crm_operator.op_get_lead(other_env, admin_lead.id)
        # write blocked too
        with self.assertRaises(AccessError):
            crm_operator.op_move_lead_stage(
                other_env, admin_lead.id, 'onboarding',
                request_text='move')
        # a lead owned by the limited user is writable
        mine = self._make_lead('Mine Co', user_id=self.limited.id)
        res = crm_operator.op_move_lead_stage(
            other_env, mine.id, 'onboarding', request_text='move mine')
        self.assertEqual(res['status'], 'done')

    def test_dispatch_rejects_unknown_intents(self):
        with self.assertRaises(UserError):
            crm_operator.dispatch(self.env, 'exec_any_python',
                                  {'lead_ids': [1]})

    def test_update_lead_whitelist(self):
        lead = self._make_lead('Whitelist Co')
        with self.assertRaises(UserError):
            crm_operator.op_update_lead(
                self.env, lead.id, {'stage_id': self.st_onboarding.id})
        res = crm_operator.op_update_lead(
            self.env, lead.id, {'expected_revenue': 50000})
        self.assertEqual(res['status'], 'done')
        self.assertEqual(lead.expected_revenue, 50000)

    def test_audit_log_has_no_unlink(self):
        """TransactionCase env is superuser — ACLs bypassed there. Use a
        plain internal user so the audit table's ACL really applies."""
        uenv = self.env(user=self.limited.id)
        uenv['prema.ai.crm.action'].check_access_rights('read')
        uenv['prema.ai.crm.action'].check_access_rights('create')
        uenv['prema.ai.crm.action'].check_access_rights('write')
        with self.assertRaises(AccessError):
            uenv['prema.ai.crm.action'].check_access_rights('unlink')

    def test_chat_created_leads_land_in_canonical_new(self):
        """_new_stage_id must resolve NEW / UNCONTACTED, never the
        folded legacy 'New'."""
        session = self.env['prema.ai.session'].create({
            'name': 'Test session',
        })
        stage_id = session._new_stage_id()
        stage = self.env['crm.stage'].browse(stage_id)
        self.assertEqual(stage.name, 'NEW / UNCONTACTED')
        self.assertFalse(stage.fold)

    def test_no_customer_email_from_audit_logging(self):
        """Audit chatter notes are internal; completing the flow must
        not create outgoing mail.mail records."""
        lead = self._make_lead('Email Safe Co')
        crm_operator.op_move_lead_stage(self.env, lead.id, 'negotiation',
                                        request_text='move')
        mail_count = self.env['mail.mail'].search_count([
            ('model', '=', 'crm.lead'), ('res_id', '=', lead.id)])
        self.assertEqual(mail_count, 0)
